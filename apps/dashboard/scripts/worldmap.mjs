// Generates lib/worldmap.ts, the land grid behind the Overview's dotted map.
// Run once by hand (not part of the build); it downloads nothing:
//
//   node apps/dashboard/scripts/worldmap.mjs <ne_110m_land.geojson> > apps/dashboard/lib/worldmap.ts
//
// Input: Natural Earth 1:110m land (public domain), e.g. from
// github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_land.geojson
// Output: one string per row of 2° cells, equirectangular, lat 84° to -58°
// (Antarctica left out), "#" where the cell centre is on land.

import { readFileSync } from "node:fs";

const CELL = 2;
const TOP = 84;
const BOTTOM = -58;
const geo = JSON.parse(readFileSync(process.argv[2], "utf8"));

const rings = [];
for (const f of geo.features) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  for (const poly of polys) rings.push(poly); // [outer, ...holes]
}

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const onLand = (lon, lat) => rings.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((h) => inRing(lon, lat, h)));

const rows = [];
for (let lat = TOP - CELL / 2; lat > BOTTOM; lat -= CELL) {
  let row = "";
  for (let lon = -180 + CELL / 2; lon < 180; lon += CELL) row += onLand(lon, lat) ? "#" : ".";
  rows.push(row);
}

console.log(`// Generated by scripts/worldmap.mjs from Natural Earth 1:110m land (public domain).
// Do not edit by hand. Equirectangular grid of ${CELL}° cells, latitude ${TOP}° to ${BOTTOM}°.

export const MAP = { cell: ${CELL}, top: ${TOP}, bottom: ${BOTTOM}, cols: ${360 / CELL}, rows: ${rows.length} } as const;

// prettier-ignore
export const LAND: readonly string[] = [
${rows.map((r) => `  "${r}",`).join("\n")}
];`);
